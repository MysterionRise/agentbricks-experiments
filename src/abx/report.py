"""Render ``reports/latest.md`` from the eval summary, the gate verdict and the cost.

The report is deterministic for a given input so a regenerated file diffs cleanly.
It carries no workspace host, user, or run URL.
"""

from __future__ import annotations

import io
import json
from datetime import UTC, datetime
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

    from databricks.sdk import WorkspaceClient

    from abx.cost import CostSummary
    from abx.gate import EvalSummary, GateVerdict

SUMMARY_FILENAME = "eval_summary.json"
REPORT_FILENAME = "latest.md"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.0f}%"


def render_report(
    summary: EvalSummary | None,
    verdict: GateVerdict | None,
    cost: CostSummary | None,
    endpoint_name: str,
    dataset_fqn: str,
    generated_at: datetime | None = None,
) -> str:
    """Build the markdown. Any missing section says why it is missing."""
    now = (generated_at or datetime.now(tz=UTC)).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = [
        "# Latest run",
        "",
        f"Generated {now}. Endpoint `{endpoint_name}`. Dataset `{dataset_fqn}`.",
        "",
        "## Eval gate",
        "",
    ]

    if summary is None or verdict is None:
        lines += [
            "**Not yet run.** Run `abx eval` against a deployed assistant to populate",
            "this section. No numbers are shown here until a real run exists.",
            "",
        ]
    else:
        status = "PASS" if verdict.passed else "FAIL"
        lines += [
            f"**Verdict: {status}** (MLflow run `{summary.run_id}`, {summary.rows} rows)",
            "",
        ]
        if verdict.reasons:
            lines += [f"- {reason}" for reason in verdict.reasons]
            lines.append("")
        lines += [
            "| Metric | Value | Scope |",
            "|---|---|---|",
            f"| Correctness | {_pct(summary.correctness_mean)} | direct + multi_doc |",
            f"| Retrieval groundedness | {_pct(summary.groundedness_mean)} | direct + multi_doc |",
            f"| Relevance to query | {_pct(summary.relevance_mean)} | all |",
            f"| Out-of-scope refusal | {_pct(summary.out_of_scope_refusal_rate)} | out_of_scope |",
            f"| Safety failures | {summary.safety_failures} | all |",
            "",
            "Rows by kind: "
            + ", ".join(f"{k} {v}" for k, v in sorted(summary.rows_by_kind.items())),
            "",
        ]
        if summary.worst:
            lines += ["### Worst rows", ""]
            for row in summary.worst:
                failed = ", ".join(s for s, v in row.scores.items() if v is False) or "none"
                lines.append(f"- **{row.question}** ({row.kind or 'unknown'}) failed: {failed}")
                if row.rationale:
                    lines.append(f"  - {row.rationale.strip()}")
            lines.append("")

    lines += ["## Cost and usage", ""]
    if cost is None:
        lines += ["**Not yet collected.** Run `abx cost` with a SQL warehouse configured.", ""]
    elif not cost.available:
        lines += [f"**Unavailable.** {cost.note}", ""]
    else:
        per_1k = cost.usd_per_1k_requests
        lines += [
            f"Window: last {cost.window_days} days.",
            "",
            "| Metric | Value |",
            "|---|---|",
            f"| Requests | {cost.requests} |",
            f"| Failed requests | {cost.failed_requests} |",
            f"| Input tokens | {cost.input_tokens} |",
            f"| Output tokens | {cost.output_tokens} |",
            f"| DBU | {cost.dbu:.2f} |",
            f"| USD (list price) | {cost.usd_list:.2f} |",
            f"| USD per 1k requests | {'n/a' if per_1k is None else f'{per_1k:.2f}'} |",
            "",
        ]

    lines += [
        "---",
        "Regenerated by `abx eval` and `abx cost`. Thresholds live in `pyproject.toml`",
        "under `[tool.abx.gate]`; see `docs/adr/0002-eval-gate.md`.",
        "",
    ]
    return "\n".join(lines)


def write_local(out_dir: Path, report: str, summary: EvalSummary | None) -> Path:
    """Write the report (and the summary JSON when given) under ``out_dir``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    report_path = out_dir / REPORT_FILENAME
    report_path.write_text(report, encoding="utf-8")
    if summary is not None:
        (out_dir / SUMMARY_FILENAME).write_text(
            json.dumps(summary.as_dict(), indent=2), encoding="utf-8"
        )
    return report_path


def write_volume(
    w: WorkspaceClient, volume_dir: str, report: str, summary: EvalSummary | None
) -> None:
    """Mirror the report into the UC volume so a CI job can fetch it."""
    w.files.create_directory(volume_dir)
    w.files.upload(
        f"{volume_dir}/{REPORT_FILENAME}", io.BytesIO(report.encode("utf-8")), overwrite=True
    )
    if summary is not None:
        payload = json.dumps(summary.as_dict(), indent=2).encode("utf-8")
        w.files.upload(f"{volume_dir}/{SUMMARY_FILENAME}", io.BytesIO(payload), overwrite=True)


def read_summary(out_dir: Path) -> EvalSummary | None:
    """Load a previously written summary so `abx cost` can keep the eval section."""
    from abx.gate import EvalSummary

    path = out_dir / SUMMARY_FILENAME
    if not path.exists():
        return None
    return EvalSummary.from_dict(json.loads(path.read_text(encoding="utf-8")))
